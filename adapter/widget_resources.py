"""Compiles our own resources (res-hu: the home-screen widgets) into hu-res/hu-resources.apk with
aapt2 and writes their IDs, as they will be after packaging (package 0x7e, merge_resources), to
hu-res/ids.json and to the Java constants class HuR."""
import json,os,re,shutil,subprocess
from pathlib import Path
from merge_resources import remap
ROOT=Path(__file__).resolve().parent;OUT=ROOT/'hu-res'
SDK=Path(os.environ.get('ANDROID_SDK_ROOT',os.environ.get('ANDROID_HOME',str(Path.home()/'Library/Android/sdk'))))
BT=SDK/'build-tools'/os.environ.get('BUILD_TOOLS_VERSION','35.0.0');JAR=SDK/'platforms/android-35/android.jar'
def build():
 shutil.rmtree(OUT,ignore_errors=True);OUT.mkdir()
 subprocess.run([str(BT/'aapt2'),'compile','--dir',str(ROOT/'res-hu'),'-o',str(OUT/'compiled.zip')],check=True)
 subprocess.run([str(BT/'aapt2'),'link','-I',str(JAR),'--manifest',str(ROOT/'res-hu/AndroidManifest.xml'),'--min-sdk-version','28','--target-sdk-version','33',
  '--emit-ids',str(OUT/'ids.txt'),'-o',str(OUT/'hu-resources.apk'),str(OUT/'compiled.zip')],check=True)
 ids={}
 for line in (OUT/'ids.txt').read_text().splitlines():
  m=re.fullmatch(r'com\.spotify\.music:(\w+)/(\w+) = (0x[0-9a-f]{8})',line.strip());assert m,line
  ids[m[1]+'/'+m[2]]=remap(int(m[3],16))
 (OUT/'ids.json').write_text(json.dumps({k:hex(v) for k,v in sorted(ids.items())},indent=1)+'\n')
 java=ROOT/'generated/local/spotify/unified/HuR.java';java.parent.mkdir(parents=True,exist_ok=True)
 java.write_text('package local.spotify.unified;\n/** Our own resources (res-hu) as packaged: package 0x7e. Generated by widget_resources.py. */\nfinal class HuR {\n private HuR(){}\n'
  +''.join(f' static final int {k.replace("/","_")}={hex(v)};\n' for k,v in sorted(ids.items()))+'}\n')
 return ids
if __name__=='__main__':print('Widget resources:',len(build()),'IDs')
